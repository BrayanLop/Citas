-- Citas: bootstrap manual de la identidad global del cliente.
-- Crea la tabla "personas" y las columnas de enlace en "Usuarios"
-- (ClaveHash / Estado / PersonaId), su FK e indice.
--
-- Necesario porque la migracion SyncUsuariosYPersonas tiene el Up()
-- vacio a proposito: estos objetos se crean a mano, no via EF.
--
-- Idempotente y seguro. Correr en la BD de CITAS (Postgres), NO en la de Natural.
-- ============================================================

-- 1) Tabla "Personas" (P mayuscula, case-sensitive; columnas en minuscula salvo "ClaveHash").
CREATE TABLE IF NOT EXISTS public."Personas" (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          text NOT NULL,
    apellido        text NOT NULL,
    cedula          text NULL,
    residencia      text NULL,
    email           text NULL,
    edad            integer NULL,
    celular         text NULL,
    fechanacimiento timestamp with time zone NULL,
    "ClaveHash"     varchar NULL
);

-- Por si la tabla ya existia sin la columna de hash:
ALTER TABLE public."Personas"
    ADD COLUMN IF NOT EXISTS "ClaveHash" varchar NULL;

-- 2) Columnas de enlace en Usuarios (EF default = PascalCase, case-sensitive).
ALTER TABLE public."Usuarios"
    ADD COLUMN IF NOT EXISTS "ClaveHash" text NULL,
    ADD COLUMN IF NOT EXISTS "Estado"    boolean NOT NULL DEFAULT true,
    ADD COLUMN IF NOT EXISTS "PersonaId" integer NULL;

-- 3) FK Usuarios.PersonaId -> personas.id (solo si no existe).
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'FK_Usuarios_personas_PersonaId'
    ) THEN
        ALTER TABLE public."Usuarios"
            ADD CONSTRAINT "FK_Usuarios_personas_PersonaId"
            FOREIGN KEY ("PersonaId") REFERENCES public."Personas" (id);
    END IF;
END $$;

-- 4) Indice de apoyo a la FK.
CREATE INDEX IF NOT EXISTS "IX_Usuarios_PersonaId"
    ON public."Usuarios" ("PersonaId");

